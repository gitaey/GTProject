-- 실행 시점: 엔티티가 바뀐 백엔드를 띄우기 "전". 로컬 application-local.yml의 DB는 운영 DB이고 ddl-auto=update라서,
--           이 SQL 없이 새 백엔드를 띄우면 Hibernate가 운영 스키마를 직접 바꾼다(아래 "ddl-auto가 대신 하면" 참고).
-- 실행 주체: 사용자(map-dev는 작성만 했다). 여러 번 실행해도 안전하다(IF NOT EXISTS / WHERE ... IS NULL).
-- 실행 방법: psql -v ON_ERROR_STOP=1 -1 -f backend/scripts/mymap/ddl-stage1.sql   (-1 = 한 트랜잭션, 실패하면 전부 되돌림)
-- 위치: 이 파일이 원본이다(저장소에 추적됨). _workspace/mymap/ddl-stage1.sql은 사본. 되돌리기: ddl-stage1-rollback.sql
--
-- ddl-auto가 대신 하면(참고):
--   · tbl_user_map에 NOT NULL int 칸 4개(progress_*, matched_count, failed_count)를 "DEFAULT 없이" 추가하려다 기존 행이 있어 실패한다
--     (Hibernate는 오류를 로그에 남기고 계속 기동 → 목록·상태 조회가 칸이 없어 500).
--   · tbl_user_map_import_failure는 만들어 주지만 인덱스는 만들지 않는다.
--   · ix_user_map_feature_map·권장 인덱스는 엔티티에 선언하지 않았으므로 만들지 않는다.
--   그래서 이 SQL을 먼저 실행하는 것이 맞다.
-- ============================================================================

-- 레이어: 업로드 종류·진행률·보고서 요약·중복 감지·지적도 기준월
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS source_kind     varchar(20);
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS progress_total  integer NOT NULL DEFAULT 0;
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS progress_done   integer NOT NULL DEFAULT 0;
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS matched_count   integer NOT NULL DEFAULT 0;
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS failed_count    integer NOT NULL DEFAULT 0;
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS file_hash       varchar(64);   -- sha256, 같은 사람이 같은 파일을 다시 올리면 경고
ALTER TABLE tbl_user_map ADD COLUMN IF NOT EXISTS parcel_version  varchar(7);    -- 매칭에 쓴 연속지적도 기준월 YYYY-MM
-- ddl-auto(Hibernate)가 먼저 칸을 만든 환경(로컬 백엔드 DevTools 재시작 등)에서는 위 ADD COLUMN이 건너뛰어져 DEFAULT가 빠진다.
-- 옛 백엔드(이 칸을 모르는 버전)가 같은 DB에 INSERT해도 실패하지 않도록 기본값을 항상 붙인다(멱등).
ALTER TABLE tbl_user_map ALTER COLUMN progress_total SET DEFAULT 0;
ALTER TABLE tbl_user_map ALTER COLUMN progress_done  SET DEFAULT 0;
ALTER TABLE tbl_user_map ALTER COLUMN matched_count  SET DEFAULT 0;
ALTER TABLE tbl_user_map ALTER COLUMN failed_count   SET DEFAULT 0;
UPDATE tbl_user_map SET source_kind = CASE source_type WHEN 'SHP' THEN 'SHP' ELSE 'EXCEL_COORD' END WHERE source_kind IS NULL;

-- 피처: 다시 매칭·내보내기용 PNU, 원본 행 번호
ALTER TABLE tbl_user_map_feature ADD COLUMN IF NOT EXISTS pnu    varchar(19);
ALTER TABLE tbl_user_map_feature ADD COLUMN IF NOT EXISTS row_no integer;
-- 지금 없음: GeoJSON 스트리밍·삭제가 전체 스캔. 피처 표가 크면 만드는 동안 그 표의 INSERT가 잠시 막힌다
-- (막히면 안 되는 시간대라면 이 한 줄만 -1 없이 CREATE INDEX CONCURRENTLY로 따로 실행)
CREATE INDEX IF NOT EXISTS ix_user_map_feature_map ON tbl_user_map_feature (user_map_id);

-- 실패 행(보고서·실패 행 엑셀). 레이어를 지우면 함께 지운다(앱이 삭제), 30일이 지나면 정리 작업이 지운다
CREATE TABLE IF NOT EXISTS tbl_user_map_import_failure (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_map_id     bigint       NOT NULL,
    row_no          integer      NOT NULL,       -- 엑셀 행 번호(머리글 = 1)
    reason_code     varchar(30)  NOT NULL,
    input_value     varchar(500),                -- 매칭에 쓴 칸의 값
    candidates_json text,                        -- AMBIGUOUS 후보 ["…", …]
    row_json        text         NOT NULL,       -- 원본 행 전체 {컬럼: 값} — 실패 행 엑셀용
    created_at      timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_umap_fail_map ON tbl_user_map_import_failure (user_map_id, row_no);
-- 30일 정리(created_at 조건)를 위한 인덱스는 만들지 않는다: 하루 한 번, 행이 수만 건 이하
-- (커지면 CREATE INDEX ix_umap_fail_created ON tbl_user_map_import_failure (created_at))

-- 기존 권장 인덱스 (references/ddl.md 6절)
CREATE INDEX IF NOT EXISTS ix_user_map_owner  ON tbl_user_map (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_umap_perm_map   ON tbl_user_map_permission_access (user_map_id);
CREATE INDEX IF NOT EXISTS ix_umap_user_map   ON tbl_user_map_user_access (user_map_id);

