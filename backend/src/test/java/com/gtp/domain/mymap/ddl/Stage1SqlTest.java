package com.gtp.domain.mymap.ddl;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import javax.sql.DataSource;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * 사용자가 운영 DB에 실행할 S1 SQL(_workspace/mymap/ddl-stage1.sql)이 (1) 문법이 맞고 두 번 실행해도 안전하며
 * (2) 실행한 결과의 칸 이름이 엔티티 매핑(Hibernate가 H2에 만든 표)과 같은지 확인한다 — 운영 DB에는 접속하지 않는다.
 * 또 ref 스키마 SQL·적재 스크립트의 중요한 약속(기본 파티션 없음, 시도코드, 비밀값 없음)을 글자로 지킨다.
 */
@DataJpaTest
class Stage1SqlTest {

    /** 저장소에 추적되는 위치(운영 DB에 실행할 이관 SQL의 원본) — _workspace는 gitignore라 거기서 읽으면 새로 받은 저장소에서 시험이 깨진다 */
    static final Path STAGE1 = Path.of("scripts/mymap/ddl-stage1.sql");
    static final Path ROLLBACK = Path.of("scripts/mymap/ddl-stage1-rollback.sql");
    static final Path REF_SQL = Path.of("scripts/mymap-ref/init-ref-schema.sql");
    static final Path LOAD_SH = Path.of("scripts/mymap-ref/load-parcel.sh");

    @Autowired
    DataSource hibernateDs;

    private static final String LEGACY_DDL = """
            CREATE TABLE tbl_user_map (
              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL, description varchar(300),
              owner_id varchar(50) NOT NULL, source_type varchar(20) NOT NULL, geom_type varchar(20), source_srid varchar(20) NOT NULL,
              status varchar(20) NOT NULL, error_message varchar(500), column_schema text, style_config text,
              visible boolean NOT NULL, feature_count integer NOT NULL, created_at timestamp, updated_at timestamp);
            CREATE TABLE tbl_user_map_feature (
              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_map_id bigint NOT NULL,
              geometry_json text NOT NULL, properties_json text);
            CREATE TABLE tbl_user_map_permission_access (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_code varchar(50) NOT NULL, user_map_id bigint NOT NULL);
            CREATE TABLE tbl_user_map_user_access (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id varchar(50) NOT NULL, user_map_id bigint NOT NULL);
            INSERT INTO tbl_user_map (name, owner_id, source_type, source_srid, status, visible, feature_count) VALUES ('옛 shp', 'a', 'SHP', 'EPSG:5186', 'READY', true, 10);
            INSERT INTO tbl_user_map (name, owner_id, source_type, source_srid, status, visible, feature_count) VALUES ('옛 엑셀', 'a', 'EXCEL', 'EPSG:4326', 'READY', true, 5);
            INSERT INTO tbl_user_map_feature (user_map_id, geometry_json) VALUES (1, '{}');
            """;

    private static Set<String> columns(Connection c, String table) throws Exception {
        Set<String> cols = new TreeSet<>();
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery("SELECT column_name FROM information_schema.columns WHERE upper(table_name) = '" + table.toUpperCase() + "'")) {
            while (rs.next()) cols.add(rs.getString(1).toLowerCase());
        }
        return cols;
    }

    @Test
    void S1_SQL은_옛_스키마에_두_번_실행해도_되고_결과_칸이_엔티티와_같다() throws Exception {
        assertThat(STAGE1).exists();
        String url = "jdbc:h2:mem:legacy_" + System.nanoTime() + ";DB_CLOSE_DELAY=-1";
        try (Connection legacy = DriverManager.getConnection(url, "sa", "");
             Connection hib = hibernateDs.getConnection()) {
            try (Statement st = legacy.createStatement()) {
                for (String s : LEGACY_DDL.split(";\\s*\\n")) if (!s.isBlank()) st.execute(s);
            }
            ScriptUtils.executeSqlScript(legacy, new FileSystemResource(STAGE1));
            ScriptUtils.executeSqlScript(legacy, new FileSystemResource(STAGE1));   // 두 번째 실행도 안전

            for (String table : List.of("tbl_user_map", "tbl_user_map_feature", "tbl_user_map_import_failure")) {
                assertThat(columns(legacy, table)).as(table + " (S1 SQL 실행 결과 = 엔티티 매핑)").isEqualTo(columns(hib, table));
            }

            try (Statement st = legacy.createStatement()) {
                ResultSet rs = st.executeQuery("SELECT name, source_kind, progress_total, progress_done, matched_count, failed_count FROM tbl_user_map ORDER BY id");
                rs.next();
                assertThat(rs.getString("source_kind")).isEqualTo("SHP");
                assertThat(rs.getInt("progress_total")).isZero();
                assertThat(rs.getInt("matched_count")).isZero();
                rs.next();
                assertThat(rs.getString("source_kind")).isEqualTo("EXCEL_COORD");   // 옛 엑셀 행은 좌표 레이어로 채운다
                rs = st.executeQuery("SELECT count(*) FROM tbl_user_map_feature WHERE pnu IS NULL AND row_no IS NULL");
                rs.next();
                assertThat(rs.getInt(1)).isEqualTo(1);                              // 옛 피처는 새 칸이 비어 있다
                // 인덱스 5개
                rs = st.executeQuery("SELECT count(*) FROM information_schema.indexes WHERE upper(index_name) IN "
                        + "('IX_USER_MAP_FEATURE_MAP','IX_UMAP_FAIL_MAP','IX_USER_MAP_OWNER','IX_UMAP_PERM_MAP','IX_UMAP_USER_MAP')");
                rs.next();
                assertThat(rs.getInt(1)).isEqualTo(5);
            }
        }
    }

    @Test
    void 되돌리기_SQL은_S1이_만든_것만_지우고_옛_스키마로_돌아간다() throws Exception {
        String url = "jdbc:h2:mem:rollback_" + System.nanoTime() + ";DB_CLOSE_DELAY=-1";
        try (Connection c = DriverManager.getConnection(url, "sa", "")) {
            try (Statement st = c.createStatement()) {
                for (String s : LEGACY_DDL.split(";\s*\n")) if (!s.isBlank()) st.execute(s);
            }
            Set<String> before = columns(c, "tbl_user_map");
            Set<String> beforeFeature = columns(c, "tbl_user_map_feature");
            ScriptUtils.executeSqlScript(c, new FileSystemResource(STAGE1));
            assertThat(columns(c, "tbl_user_map")).hasSizeGreaterThan(before.size());
            ScriptUtils.executeSqlScript(c, new FileSystemResource(ROLLBACK));
            assertThat(columns(c, "tbl_user_map")).isEqualTo(before);
            assertThat(columns(c, "tbl_user_map_feature")).isEqualTo(beforeFeature);
            assertThat(columns(c, "tbl_user_map_import_failure")).isEmpty();
            try (Statement st = c.createStatement()) {
                ResultSet rs = st.executeQuery("SELECT count(*) FROM tbl_user_map");
                rs.next();
                assertThat(rs.getInt(1)).isEqualTo(2);   // 되돌려도 레이어 행 자체는 그대로
            }
        }
    }

    @Test
    void S1_SQL은_운영_데이터를_지우거나_표를_없애는_문장이_없다() throws Exception {
        assertThat(STAGE1).exists();
        String sql = String.join("\n", Files.readAllLines(STAGE1)).toLowerCase();
        String code = java.util.Arrays.stream(sql.split("\n")).filter(l -> !l.trim().startsWith("--")).reduce("", (a, b) -> a + "\n" + b);
        assertThat(code).doesNotContain("drop table").doesNotContain("drop column").doesNotContain("truncate").doesNotContain("delete from");
        // 허용하는 ALTER COLUMN은 SET DEFAULT뿐 — ddl-auto가 먼저 만든 칸에 기본값을 붙이는 용도(타입 변경·NOT NULL 해제 등은 금지)
        assertThat(code.lines().filter(l -> l.contains("alter column")).allMatch(l -> l.contains("set default"))).isTrue();
    }

    @Test
    void ref_스키마_SQL의_약속() throws Exception {
        String sql = Files.readString(REF_SQL);
        // 기본(DEFAULT) 파티션이 있으면 DETACH PARTITION ... CONCURRENTLY가 막힌다 — 두지 않는다
        assertThat(sql.toLowerCase()).doesNotContain("partition of ref.lsmd_cont_ldreg default").doesNotContain("for values in (default");
        assertThat(sql).doesNotContainPattern("(?i)PARTITION OF [a-z_.]+ DEFAULT");
        // 시도코드 20개(현행 17 + 신규 12 + 옛 29·46·42·45)
        for (String c : List.of("11", "12", "26", "27", "28", "29", "30", "31", "36", "41", "42", "43", "44", "45", "46", "47", "48", "50", "51", "52")) {
            assertThat(sql).as("시도코드 " + c).contains("'" + c + "'");
        }
        // VWorld 컬럼 매핑 결과
        for (String col : List.of("pnu", "sido", "bjd_code", "bjd_name", "jibun", "jibun_jimok", "base_date", "sgg_code", "geom")) {
            assertThat(sql).as(col).containsPattern("(?m)^\\s+" + col + "\\s");
        }
        assertThat(sql).contains("PARTITION BY LIST (sido)").contains("geometry(MultiPolygon, 4326)").contains("ref.load_meta");
        assertThat(sql).doesNotContainPattern("(?i)USING\\s+gist");   // 1단계에는 공간 인덱스를 만들지 않는다
    }

    @Test
    void 적재_스크립트에_접속_정보_비밀번호가_없다() throws Exception {
        List<String> code = Files.readAllLines(LOAD_SH).stream().filter(l -> !l.trim().startsWith("#")).toList();
        assertThat(code).noneMatch(l -> l.toLowerCase().matches(".*password\\s*=.*"));
        assertThat(code).noneMatch(l -> l.contains("jdbc:postgresql"));
        // 접속 정보는 환경 변수에서만 읽는다 — PGHOST=값 같은 대입이 스크립트에 없어야 한다
        assertThat(code).noneMatch(l -> l.matches(".*\\bPG(HOST|PORT|USER|DATABASE|PASSWORD)=\\S.*"));
    }
}
